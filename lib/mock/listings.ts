function img(seed: string, n: number) {
  return Array.from({ length: n }, (_, i) => ({
    id: `${seed}-img-${i}`,
    listing_id: seed,
    uri: `https://picsum.photos/seed/${seed}-${i}/900/650`,
    position: i,
  }));
}

function faq(pairs: [string, string][]) {
  return pairs.map(([question, answer]) => ({ question, answer }));
}

